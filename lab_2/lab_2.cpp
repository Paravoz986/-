#include <iostream>
#include <cmath>

using namespace std;

int main()
{
    // Вхідні дані
    int M;
    cout << "Введіть масу в кілограмах (M): ";
    cin >> M;

    // Обчислення за алгоритмом
    int T = M / 1000;     // Кількість повних тонн (цілочисельне ділення)
    int K = M % 1000;     // Надлишок кілограмів (остача від ділення)

    // Виведення результатів з поясненнями
    cout << "Повнітони (T): " << T << " т" << endl;
    cout << "Надлишок кілограмів (K): " << K << " кг" << endl;

    return 0;
}